"""The gruntz-decomp target: what concord reads from a checkout laid out as
`gruntz build` leaves it, and, where a built checkout is available, that its
candidate compiles score as the checkout's own report does.

The checkout tests run when CONCORD_GRUNTZ names a gruntz-decomp checkout after
`gruntz build`, or one is at ../gruntz-decomp, and skip otherwise.
"""

import json
import os
import stat
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from concord.gruntz import REPORT, Gruntz, shell_command
from concord.permute import near_misses, singles
from concord.search import attributed_lines
from concord.transforms import name_temporaries

SWITCH_DOWN = "?SwitchDown@CSwitch@@UAEHXZ"
SWITCH_UP = "?SwitchUp@CSwitch@@UAEHXZ"
SOURCE = b"""#include <StdAfx.h>

RVA(0x00110570, 0x20)
i32 CSwitch::SwitchDown() {
    i32 tile = m_tile;
    if (tile < m_limit) {
        return Lower(tile);
    }
    return 0;
}

RVA(0x001106b0, 0x10)
i32 CSwitch::SwitchUp() {
    return m_tile + 1;
}
"""
BINDINGS = (
    "# GENERATED by gruntz.model - the resolved claim set (the delink key).\n"
    "rva\tsize\tkind\tspace\tname\tunit\tchannel\talso_units\taliases\n"
    "0x00001000\t0x5\tthunk\ttext\t\t\t\t\t\n"
    f"0x00110570\t0x20\t\ttext\t{SWITCH_DOWN}\tswitch\tsrc\t\t\n"
    f"0x001106b0\t0x10\t\ttext\t{SWITCH_UP}\tswitch\tsrc\t\t\n"
    "0x00200000\t0x4\t\tdata\t?g_count@@3HA\tswitch\tsrc\t\t\n"
)
UNITS = '[flags]\ncpp = ["/nologo", "/c", "/O2"]\n\n[[unit]]\nunit = "switch"\nsource = "src/Gruntz/Switch.cpp"\nflags = "cpp"\n'


def checkout(root: Path, functions: list[dict], baseline: str) -> Gruntz:
    """A directory with the files concord reads from a built gruntz-decomp checkout."""
    (root / REPORT).parent.mkdir(parents=True)
    (root / REPORT).write_text(json.dumps({"units": [{"name": "switch", "functions": functions}]}))
    (root / "build/gen").mkdir(parents=True)
    (root / "build/gen/bindings.tsv").write_text(BINDINGS)
    (root / "config").mkdir()
    (root / "config/units.toml").write_text(UNITS)
    (root / "config/match_baseline.tsv").write_text("# gruntz match baseline\nswitch\t2\t1\n" + baseline)
    (root / "src/Gruntz").mkdir(parents=True)
    (root / "src/Gruntz/Switch.cpp").write_bytes(SOURCE)
    return Gruntz(root)


class CheckoutFiles(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name)
        self.gruntz = checkout(
            self.root,
            [
                {"name": SWITCH_DOWN, "size": "32", "fuzzy_match_percent": 97.5},
                {"name": SWITCH_UP, "size": "16", "fuzzy_match_percent": 98.0},
                {"name": "__ehreg$L1", "size": "8", "fuzzy_match_percent": 50.0},
                {"name": "?Reset@CSwitch@@QAEXXZ", "size": "8", "fuzzy_match_percent": 100.0},
            ],
            f"switch\t{SWITCH_DOWN}\t97.5000\t97.5000\t3\tabc\t0x110570\t99.0000\t\n"
            f"switch\t{SWITCH_UP}\t100.0000\t98.0000\t1\tdef\t0x1106b0\t100.0000\t\n"
            "switch\t?Reset@CSwitch@@QAEXXZ\t97.0000\t97.0000\t2\tfed\t0x110700\t97.0000\t\n",
        )

    def test_a_function_is_exact_when_its_present_source_has_scored_100(self):
        verdicts = {v.symbol: v.row for v in self.gruntz.verdicts()}
        reset = "?Reset@CSwitch@@QAEXXZ"
        self.assertEqual(set(verdicts), {SWITCH_DOWN, SWITCH_UP, reset})  # the exception-handling funclet is no target
        self.assertFalse(verdicts[SWITCH_DOWN]["exact"])
        self.assertTrue(verdicts[SWITCH_UP]["exact"])  # scores 98 in this build, banked at 100
        self.assertTrue(verdicts[reset]["exact"])  # scores 100 in this build, not banked yet
        self.assertEqual((verdicts[SWITCH_DOWN]["address"], verdicts[SWITCH_DOWN]["size"]), ("0x110570", 32))

    def test_a_unit_is_named_by_its_stem_or_its_source(self):
        self.assertEqual(self.gruntz.source("switch"), "src/Gruntz/Switch.cpp")
        self.assertEqual(self.gruntz.source("src/Gruntz/Switch.cpp"), "src/Gruntz/Switch.cpp")
        self.assertEqual(self.gruntz.source_path("switch"), self.root.resolve() / "src/Gruntz/Switch.cpp")
        with self.assertRaises(KeyError):
            self.gruntz.source("src/Gruntz/Missing.cpp")

    def test_a_function_is_found_by_its_address_label(self):
        self.assertTrue(self.gruntz.find_function(SOURCE, SWITCH_DOWN).text.startswith(b"i32 CSwitch::SwitchDown()"))
        self.assertTrue(self.gruntz.find_function(SOURCE, SWITCH_UP).text.startswith(b"i32 CSwitch::SwitchUp()"))
        with self.assertRaises(KeyError):
            self.gruntz.find_function(SOURCE, "?Missing@@YAXXZ")
        with self.assertRaises(KeyError):  # the symbol has an address, and this source has no label for it
            self.gruntz.find_function(b"int unrelated;\n", SWITCH_UP)

    def test_rewrites_apply_inside_the_labelled_function(self):
        found = singles(SOURCE, SWITCH_DOWN, set(), self.gruntz.find_function, self.gruntz.rewrites)
        self.assertTrue(any(b"m_limit > tile" in text for text, _ in found))
        for text, _ in found:
            self.assertEqual(text[text.index(b"RVA(0x001106b0") :], SOURCE[SOURCE.index(b"RVA(0x001106b0") :])
            self.assertNotIn(b"__typeof__", text)  # a GCC extension cl 5.0 rejects
        self.assertNotIn(name_temporaries, self.gruntz.rewrites)

    def test_a_checkout_without_a_report_is_refused(self):
        (self.root / REPORT).unlink()
        with self.assertRaisesRegex(FileNotFoundError, "gruntz build"):
            Gruntz(self.root)


class DevShell(unittest.TestCase):
    def test_the_environment_names_the_shell(self):
        with patch.dict(os.environ, {"CONCORD_GRUNTZ_SHELL": "ssh builder 'cd /g && nix develop --command'"}):
            self.assertEqual(shell_command(Path("/g")), ["ssh", "builder", "cd /g && nix develop --command"])

    def test_an_installed_nix_is_used_directly(self):
        with tempfile.TemporaryDirectory() as tmp:
            nix = Path(tmp) / "nix"
            nix.write_text("#!/bin/sh\n")
            nix.chmod(nix.stat().st_mode | stat.S_IXUSR)
            with patch.dict(os.environ, {"PATH": tmp, "CONCORD_GRUNTZ_SHELL": ""}):
                self.assertEqual(shell_command(Path("/g")), ["nix", "develop", "/g", "--command"])


def built_checkout() -> Path | None:
    root = Path(os.environ.get("CONCORD_GRUNTZ", Path(__file__).resolve().parents[2] / "gruntz-decomp"))
    return root if (root / REPORT).is_file() else None


@unittest.skipUnless(built_checkout(), "needs a gruntz-decomp checkout after `gruntz build`")
class BuiltCheckout(unittest.TestCase):
    """The unchanged source of a unit, compiled as a candidate, must score as the
    checkout's own report does: the report is the authority."""

    UNIT = "tileswitchlogic"

    @classmethod
    def setUpClass(cls):
        cls.gruntz = Gruntz(built_checkout())
        cls.evaluation = cls.gruntz.evaluate(cls.UNIT, {"baseline": cls.gruntz.source_path(cls.UNIT).read_bytes()})["baseline"]

    def test_the_unchanged_source_scores_as_the_report_does(self):
        self.assertEqual(self.evaluation.error, "")
        self.assertIn("objdiff_scores", self.gruntz.using)  # the dev shell has rustc, so this checks the Rust reader
        self.assertEqual("wibo" in self.gruntz.using, bool(os.environ.get("CONCORD_GRUNTZ_WIBO")))
        reported = {v.symbol: v.row["fuzzy"] for v in self.gruntz.verdicts(self.UNIT)}
        scored = {symbol: score for symbol, score in self.evaluation.fuzzy.items() if symbol in reported}
        self.assertGreater(len(scored), 40)
        for symbol, score in scored.items():
            self.assertAlmostEqual(score, reported[symbol], places=3, msg=symbol)

    def test_only_functions_scoring_100_are_exact(self):
        exact = self.evaluation.exact_functions()
        self.assertTrue(exact)
        self.assertTrue(all(self.evaluation.fuzzy[symbol] == 100.0 for symbol in exact))

    def test_an_inexact_function_has_attributed_findings(self):
        verdict = next(v for v in self.gruntz.verdicts(self.UNIT) if not v.row["exact"])
        result = self.gruntz.diff(verdict)
        self.assertFalse(result.exact)
        self.assertTrue(result.findings)
        candidate = self.gruntz.diff(self.evaluation.verdict(verdict.symbol), self.evaluation.object)
        self.assertEqual([f.cause for f in candidate.findings], [f.cause for f in result.findings])

    def test_a_difference_is_attributed_to_lines_of_its_function(self):
        verdict = next(v for v in self.gruntz.verdicts(self.UNIT) if not v.row["exact"])
        source = self.gruntz.source_path(self.UNIT).read_bytes()
        scope = self.gruntz.find_function(source, verdict.symbol)
        result = self.gruntz.diff(self.evaluation.verdict(verdict.symbol), self.evaluation.object)
        lines = attributed_lines(self.gruntz, self.UNIT, verdict.symbol, source, result)
        self.assertTrue(lines)
        for line in lines:
            self.assertTrue(scope.start_point.row + 1 <= line <= scope.end_point.row + 1, line)

    def test_a_source_that_does_not_compile_reports_the_compiler_error(self):
        broken = self.gruntz.source_path(self.UNIT).read_bytes() + b"\nthis is not C++;\n"
        evaluation = self.gruntz.evaluate(self.UNIT, {"broken": broken})["broken"]
        self.assertIn("error", evaluation.error)
        self.assertIsNone(evaluation.object)

    def test_near_misses_are_inexact_functions_defined_in_their_units(self):
        verdicts = list(self.gruntz.verdicts(self.UNIT))  # one unit's, to keep the test short
        with patch.object(self.gruntz, "verdicts", lambda: iter(verdicts)):
            found = near_misses(self.gruntz, 90.0)
        self.assertTrue(found)
        inexact = {v.symbol for v in verdicts if not v.row["exact"]}
        for unit, symbol, score in found:
            self.assertEqual(unit, "src/Gruntz/TileTriggerSwitchLogic.cpp")
            self.assertIn(symbol, inexact)
            self.assertTrue(90.0 <= score < 100.0)


if __name__ == "__main__":
    unittest.main()
